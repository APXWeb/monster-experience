// Catalog interaction review: node scripts/interact.mjs <url> <out> <w> <h> [mobile]
import { chromium, devices } from 'playwright-core'
import fs from 'node:fs'
import path from 'node:path'
const [url, out, w, h, mobile] = process.argv.slice(2)
fs.mkdirSync(out, { recursive: true })
const exe = path.join(process.env.LOCALAPPDATA, 'ms-playwright', 'chromium-1243', 'chrome-win64', 'chrome.exe')
const browser = await chromium.launch({ executablePath: exe, headless: true, args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'] })
const ctx = await browser.newContext(mobile ? { ...devices['Pixel 7'], viewport: { width: +w, height: +h } } : { viewport: { width: +w, height: +h } })
const page = await ctx.newPage()
const logs = []
page.on('console', (m) => m.type() === 'error' && logs.push(m.text()))
page.on('pageerror', (e) => logs.push('pageerror ' + e.message))
await page.goto(url, { waitUntil: 'networkidle' })
await page.waitForFunction(() => !document.querySelector('.loader'), null, { timeout: 20000 }).catch(() => {})
const jump = async (sel, off = 0) => {
  const y = await page.evaluate(([s, o]) => document.querySelector(s).getBoundingClientRect().top + scrollY + o, [sel, off])
  await page.evaluate((y) => window.__scroll.jump(y), y)
  await page.waitForTimeout(1500)
}
const shot = (n) => page.screenshot({ path: path.join(out, n + '.jpg'), type: 'jpeg', quality: 82 })
await jump('#bridge')
await shot('a-catalog-top')
await jump('#sabores-stage', -90)
await shot('b-stage')
await page.click('.filter:has-text("Juice Monster")')
await page.waitForTimeout(1400)
await shot('c-filter-juice')
await page.click('.thumb:nth-child(2)')
await page.waitForTimeout(1400)
await shot('d-select-2')
await page.hover('.thumb:nth-child(4)')
await page.mouse.move(0, 0)
await page.click('text=Ver ficha completa')
await page.waitForTimeout(1500)
await shot('e-detail')
await page.click('.detail-step-next')
await page.waitForTimeout(1400)
await shot('f-detail-next')
const focusOk = await page.evaluate(() => !!document.activeElement?.closest('.detail-panel'))
await page.keyboard.press('Escape')
await page.waitForTimeout(900)
await shot('g-closed')
await page.click('.filter:has-text("Dragon Tea")')
await page.waitForTimeout(1200)
const names = await page.$$eval('.thumb-name', (els) => els.map((e) => e.textContent))
await page.click('.filter:has-text("Todas")')
await page.waitForTimeout(600)
const all = await page.$$eval('.thumb', (els) => els.length)
console.log(JSON.stringify({ dragon: names, all, focusOk, errors: logs }, null, 1))
await browser.close()
